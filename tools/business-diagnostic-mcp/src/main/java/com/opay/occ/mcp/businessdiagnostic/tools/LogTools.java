package com.opay.occ.mcp.businessdiagnostic.tools;

import com.opay.occ.mcp.businessdiagnostic.core.LogConfig;
import com.opay.occ.mcp.businessdiagnostic.core.LogEnv;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Instant;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Calendar;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TimeZone;
import java.util.concurrent.TimeUnit;

/**
 * Log diagnostics against the {@code test_log} table.
 *
 * <p>Only structured conditions are accepted; the SQL is generated by
 * {@link SqlBuilder} and every value is bound as a JDBC parameter.</p>
 */
public final class LogTools {

    public static final int DEFAULT_WINDOW_MINUTES = 20;
    public static final int DEFAULT_LIMIT = 200;
    public static final int MAX_LIMIT = 1000;
    public static final int MAX_TRACE_IDS = 20;

    private static final int QUERY_TIMEOUT_SECONDS = 5;
    private static final String LOG_TIME_FORMAT = "yyyy-MM-dd HH:mm:ss.SSS";
    private static final List<String> LOG_COLUMNS = Arrays.asList(
            "id", "service_name", "pod", "log_time", "trace_id", "log_level", "content");

    private LogTools() {
    }

    /** Tool: list_log_environments */
    public static Map<String, Object> listEnvironments(LogConfig config) {
        List<Map<String, Object>> environments = new ArrayList<>();
        for (LogEnv env : config.getEnvironments().values()) {
            Map<String, Object> item = new LinkedHashMap<>();
            item.put("name", env.getName());
            item.put("mysqlHost", env.getMysqlHost());
            item.put("mysqlDatabase", env.getMysqlDatabase());
            item.put("logTimeZone", env.getLogTimeZone());
            item.put("apolloAppId", env.getApolloAppId());
            item.put("apolloMeta", env.getApolloMeta());
            item.put("apolloNamespaces", env.getApolloNamespaces());
            environments.add(item);
        }
        Map<String, Object> response = new LinkedHashMap<>();
        response.put("ok", true);
        response.put("defaultEnvironment", config.getDefaultEnvironment());
        response.put("logTable", config.getLogTable());
        response.put("services", new LinkedHashMap<>(config.getServices()));
        response.put("environments", environments);
        if (!config.getBlockedEnvironments().isEmpty()) {
            response.put("blockedEnvironments", new ArrayList<>(config.getBlockedEnvironments()));
            response.put("warnings", Collections.singletonList(
                    "Production environments are not loaded; these diagnostics are test-only: "
                            + config.getBlockedEnvironments()));
        }
        return response;
    }

    /** Tool: query_logs */
    public static Map<String, Object> query(LogConfig config, String env, String service,
                                            String traceId, String keyword, String logLevel,
                                            Long timeStart, Long timeEnd, int limit, String order) {
        if (isBlank(traceId) && isBlank(keyword)) {
            throw new IllegalArgumentException("Either traceId or keyword is required");
        }
        LogEnv logEnv = config.requireEnvironment(env);
        List<String> services = config.resolveServices(service);
        String table = config.getLogTable();
        ZoneId zone = logEnv.getLogTimeZoneId();
        long[] window = resolveTimeWindow(timeStart, timeEnd, System.currentTimeMillis());
        List<SqlBuilder.SqlQuery> queries = buildQuery(
                table, services, traceId, keyword, logLevel, window[0], window[1], limit, order, zone);

        String password = logEnv.getMysqlPassword();
        if (password == null || password.isEmpty()) {
            throw new IllegalStateException(
                    "Missing password environment variable: " + logEnv.getMysqlPasswordEnv());
        }

        List<Map<String, Object>> rows = new ArrayList<>();
        try (Connection connection = JdbcSupport.openReadOnly(
                logEnv.getMysqlHost(), logEnv.getMysqlPort(), logEnv.getMysqlDatabase(),
                logEnv.getMysqlUser(), password)) {
            for (SqlBuilder.SqlQuery query : queries) {
                rows.addAll(executeQuery(connection, query, zone));
            }
        } catch (SQLException e) {
            throw new IllegalStateException("MySQL log query failed: " + e.getMessage(), e);
        }

        boolean hasMore = rows.size() > limit;
        List<Map<String, Object>> page = hasMore ? new ArrayList<>(rows.subList(0, limit)) : rows;
        List<String> contents = new ArrayList<>();
        Map<String, Integer> serviceHits = new LinkedHashMap<>();
        for (Map<String, Object> row : page) {
            Object content = row.get("content");
            contents.add(content == null ? null : content.toString());
            String serviceName = String.valueOf(row.get("serviceName"));
            serviceHits.put(serviceName, serviceHits.containsKey(serviceName) ? serviceHits.get(serviceName) + 1 : 1);
        }

        Map<String, Object> response = new LinkedHashMap<>();
        response.put("ok", true);
        response.put("env", logEnv.getName());
        response.put("logTimeZone", logEnv.getLogTimeZone());
        response.put("table", table);
        response.put("services", services);
        response.put("traceId", traceId);
        response.put("keyword", keyword);
        response.put("timeStart", format(window[0], zone));
        response.put("timeEnd", format(window[1], zone));
        response.put("rows", page);
        response.put("rowCount", page.size());
        response.put("serviceHits", serviceHits);
        response.put("matchedTraceIds", TraceIdExtractor.topTraceIds(contents, MAX_TRACE_IDS));
        response.put("hasMore", hasMore);
        response.put("queryCount", queries.size());
        return response;
    }

    /** Defaults to the last {@value #DEFAULT_WINDOW_MINUTES} minutes when no time is provided. */
    static long[] resolveTimeWindow(Long timeStart, Long timeEnd, long nowMillis) {
        long end = timeEnd != null ? timeEnd : nowMillis;
        long start = timeStart != null ? timeStart : end - TimeUnit.MINUTES.toMillis(DEFAULT_WINDOW_MINUTES);
        if (start > end) {
            throw new IllegalArgumentException("timeStart must be less than or equal to timeEnd");
        }
        return new long[]{start, end};
    }

    static List<SqlBuilder.SqlQuery> buildQuery(String table, List<String> services, String traceId,
                                                String keyword, String logLevel, long startMillis,
                                                long endMillis, int limit, String order, ZoneId zone) {
        if (limit < 1 || limit > MAX_LIMIT) {
            throw new IllegalArgumentException("limit must be between 1 and " + MAX_LIMIT);
        }
        if (services == null || services.isEmpty()) {
            throw new IllegalArgumentException("services must not be empty");
        }

        List<Object> serviceValues = new ArrayList<>(services);
        List<Map<String, Object>> where = new ArrayList<>();
        where.add(condition("service_name", "in", serviceValues));
        if (!isBlank(traceId)) {
            where.add(condition("trace_id", "eq", traceId.trim()));
        }
        if (!isBlank(logLevel)) {
            where.add(condition("log_level", "eq", logLevel.trim().toUpperCase()));
        }
        if (!isBlank(keyword)) {
            where.add(condition("content", "like", "%" + keyword.trim() + "%"));
        }
        // MySQL compares DATETIME columns correctly against formatted string literals;
        // passing epoch millis would be converted into YYYYMMDDHHMMSS and break the range.
        where.add(condition("log_time", "gte", format(startMillis, zone)));
        where.add(condition("log_time", "lte", format(endMillis, zone)));

        List<Map<String, Object>> orderBy = Collections.singletonList(
                orderBy("log_time", "desc".equalsIgnoreCase(order) ? "desc" : "asc"));

        return SqlBuilder.buildSelect(table, LOG_COLUMNS, where, orderBy, limit, 0);
    }

    private static List<Map<String, Object>> executeQuery(Connection connection, SqlBuilder.SqlQuery query,
                                                          ZoneId zone) throws SQLException {
        List<Map<String, Object>> rows = new ArrayList<>();
        try (PreparedStatement statement = JdbcSupport.prepareReadOnly(connection, query.getSql())) {
            statement.setQueryTimeout(QUERY_TIMEOUT_SECONDS);
            List<Object> params = query.getParams();
            for (int i = 0; i < params.size(); i++) {
                statement.setObject(i + 1, params.get(i));
            }
            try (ResultSet resultSet = statement.executeQuery()) {
                while (resultSet.next()) {
                    Map<String, Object> row = new LinkedHashMap<>();
                    row.put("id", resultSet.getLong("id"));
                    row.put("serviceName", resultSet.getString("service_name"));
                    row.put("pod", resultSet.getString("pod"));
                    // The stored value is a zone-less DATETIME; interpret it with the
                    // environment's log time zone so the epoch millis are correct.
                    java.sql.Timestamp logTime = resultSet.getTimestamp(
                            "log_time", Calendar.getInstance(TimeZone.getTimeZone(zone)));
                    long logTimeMillis = logTime == null ? 0L : logTime.getTime();
                    row.put("logTime", format(logTimeMillis, zone));
                    row.put("logTimeMillis", logTimeMillis);
                    row.put("traceId", resultSet.getString("trace_id"));
                    row.put("logLevel", resultSet.getString("log_level"));
                    row.put("content", resultSet.getString("content"));
                    rows.add(row);
                }
            }
        }
        return rows;
    }

    private static Map<String, Object> condition(String field, String op, Object value) {
        Map<String, Object> condition = new LinkedHashMap<>();
        condition.put("field", field);
        condition.put("op", op);
        condition.put("value", value);
        return condition;
    }

    private static Map<String, Object> orderBy(String field, String direction) {
        Map<String, Object> order = new LinkedHashMap<>();
        order.put("field", field);
        order.put("direction", direction);
        return order;
    }

    /** Formats an instant in the given zone, e.g. {@code 2025-10-09 16:53:20.000}. */
    private static String format(long millis, ZoneId zone) {
        return DateTimeFormatter.ofPattern(LOG_TIME_FORMAT).withZone(zone)
                .format(Instant.ofEpochMilli(millis));
    }

    private static boolean isBlank(String value) {
        return value == null || value.trim().isEmpty();
    }
}
